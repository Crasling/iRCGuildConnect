local function normalize(value)
    local text = tostring(value or ""):lower()
    for _, pair in ipairs(unicodeCaseFolds) do text = text:gsub(pair[1], pair[2]) end
    return text
end

function iRC:ContainsProfanity(value)
    local text = normalize(value)
    if text == "" then return false end
    for token in text:gmatch("[^%s%p]+") do
        if blockedWords[token] then return true, token end
    end
    for _, fragment in ipairs(blockedFragments) do
        if text:find(fragment, 1, true) then return true, fragment end
    end
    return false
end
